// Generates src/term/zeroWidth.ts: code point ranges that occupy no terminal column
// (non-spacing and enclosing marks, format characters), from this Node's Unicode data.
// Run: node scripts/gen-zero-width.ts
import { writeFileSync } from "node:fs";

const mark = /^[\p{Mn}\p{Me}]$/u;
const format = /^\p{Cf}$/u;
const isZero = (cp: number): boolean => {
  if (cp === 0x200b || cp === 0x200c || cp === 0x200d || cp === 0x2060 || cp === 0xfeff) return true;
  if ((cp >= 0xfe00 && cp <= 0xfe0f) || (cp >= 0xe0100 && cp <= 0xe01ef)) return true;
  if (cp >= 0x1160 && cp <= 0x11ff) return true;
  if (cp >= 0xd800 && cp <= 0xdfff) return false;
  const ch = String.fromCodePoint(cp);
  if (mark.test(ch)) return true;
  if (format.test(ch)) return cp !== 0x00ad && !(cp >= 0x0600 && cp <= 0x0605) && cp !== 0x06dd && cp !== 0x110bd;
  return false;
};

const ranges: number[] = [];
for (let cp = 0x300; cp <= 0x10ffff; cp++) {
  if (!isZero(cp)) continue;
  if (ranges.length && ranges[ranges.length - 1] === cp - 1) ranges[ranges.length - 1] = cp;
  else ranges.push(cp, cp);
}
const body = [];
for (let i = 0; i < ranges.length; i += 8) body.push("  " + ranges.slice(i, i + 8).map((n) => "0x" + n.toString(16)).join(", ") + ",");
writeFileSync(
  new URL("../src/term/zeroWidth.ts", import.meta.url),
  `// Generated by scripts/gen-zero-width.ts from Unicode ${process.versions.unicode}. Do not edit.\n` +
    `/** Sorted [first, last] pairs of zero-width code points (marks and format characters). */\n` +
    `export const ZERO_WIDTH: readonly number[] = [\n${body.join("\n")}\n];\n`,
);
console.log(`${ranges.length / 2} ranges, Unicode ${process.versions.unicode}`);
